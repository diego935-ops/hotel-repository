// Dynamic I18N Engine
function applyLanguage(lang) {
    currentLanguage = lang;
    const dict = TRANSLATIONS[lang] || TRANSLATIONS['English'];

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.textContent = dict[key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.placeholder = dict[key];
        }
    });

    updateShopHeaderTitle();
    renderShopPageGrid();
    updateCartUI();
    renderWishlistTab();
    if (activePdpProduct) {
        renderProductDetailTab(activePdpProduct.id);
    }
}

function formatPrice(idrPrice) {
    const curr = CURRENCIES[currentCurrency] || CURRENCIES.IDR;
    const converted = idrPrice * curr.rate;

    if (curr.code === 'IDR') {
        return `${curr.symbol}${Math.round(converted).toLocaleString('id-ID')}`;
    } else if (curr.code === 'MYR') {
        return `${curr.symbol}${converted.toFixed(2)}`;
    } else if (curr.code === 'SGD') {
        return `${curr.symbol}${converted.toFixed(2)}`;
    }
    return `${curr.symbol}${converted.toLocaleString()}`;
}

// Shop Filtering & Rendering
function renderShopPageGrid() {
    const grid = document.getElementById('shop-page-products-grid');
    const emptyState = document.getElementById('shop-empty-state');
    if (!grid) return;

    grid.innerHTML = '';

    let filtered = PRODUCTS.filter(p => {
        if (filterState.searchQuery) {
            const q = filterState.searchQuery.toLowerCase();
            if (!p.title.toLowerCase().includes(q) && !p.category.toLowerCase().includes(q)) {
                return false;
            }
        }

        if (filterState.categories.length > 0) {
            if (!filterState.categories.includes(p.category)) {
                return false;
            }
        }

        if (filterState.productType === 'FEATURED' && p.type !== 'FEATURED') return false;
        if (filterState.productType === 'DISCOUNT' && p.type !== 'DISCOUNT') return false;

        if (filterState.stockStatus === 'IN_STOCK' && !p.inStock) return false;

        if (filterState.priceMin !== null && p.priceIDR < filterState.priceMin) return false;
        if (filterState.priceMax !== null && p.priceIDR > filterState.priceMax) return false;

        return true;
    });

    if (filterState.sortBy === 'low_high') {
        filtered.sort((a, b) => a.priceIDR - b.priceIDR);
    } else if (filterState.sortBy === 'high_low') {
        filtered.sort((a, b) => b.priceIDR - a.priceIDR);
    }

    if (filtered.length === 0) {
        emptyState.classList.remove('hidden');
    } else {
        emptyState.classList.add('hidden');
        const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS['English'];

        filtered.forEach(p => {
            const isFav = wishlist.has(p.id);
            const formattedPrice = formatPrice(p.priceIDR);
            const buyText = dict.btn_buy || 'Beli';

            const card = document.createElement('div');
            card.className = 'bg-[#f0f0ee] border border-zinc-200/80 rounded-xl p-3 flex flex-col justify-between group hover:shadow-md transition-shadow relative';
            
            card.innerHTML = `
                <!-- Image Container -> Opens PDP Tab on Click -->
                <div onclick="showSection('pdp', ${p.id})" class="relative w-full h-64 bg-zinc-200 rounded-lg overflow-hidden mb-3 cursor-pointer">
                    <img src="${p.img}" alt="${p.title}" class="w-full h-full object-cover object-top group-hover:scale-105 transition-transform duration-500">
                    <button onclick="event.stopPropagation(); toggleWishlist(${p.id})" class="absolute bottom-2.5 right-2.5 p-1.5 rounded-full bg-black/20 hover:bg-black/40 text-white backdrop-blur-sm transition-colors">
                        <i data-lucide="heart" class="w-4 h-4 ${isFav ? 'fill-red-500 text-red-500' : 'text-white'}"></i>
                    </button>
                </div>

                <!-- Product Details Title -> Opens PDP Tab on Click -->
                <div class="space-y-1 mb-2 px-1">
                    <h4 onclick="showSection('pdp', ${p.id})" class="text-xs font-normal text-zinc-800 tracking-tight cursor-pointer hover:underline line-clamp-1">${p.title}</h4>
                    <p class="text-xs font-normal text-[#b88b2a] font-mono">${formattedPrice}</p>
                </div>

                <!-- Action Button -> Opens PDP Tab or Direct Add -->
                <div class="flex justify-end pt-1 px-1">
                    <button onclick="showSection('pdp', ${p.id})" class="text-xs font-medium text-[#b88b2a] hover:text-[#a0741e] transition-colors focus:outline-none">
                        ${buyText}
                    </button>
                </div>
            `;
            grid.appendChild(card);
        });
    }

    lucide.createIcons();
}

// PDP Render Function
function renderProductDetailTab(productId) {
    const product = PRODUCTS.find(p => p.id === productId);
    if (!product) return;

    activePdpProduct = product;
    selectedSize = 'M';
    pdpQuantity = 1;

    const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS['English'];

    // Update Elements
    document.getElementById('pdp-page-category-crumb').innerText = product.category;
    document.getElementById('pdp-page-category').innerText = product.category;
    document.getElementById('pdp-page-title').innerText = product.title;
    document.getElementById('pdp-page-price').innerText = formatPrice(product.priceIDR);
    document.getElementById('pdp-page-image').src = product.img;
    document.getElementById('pdp-thumb-1').src = product.img;
    document.getElementById('pdp-thumb-2').src = product.img;
    document.getElementById('pdp-page-desc').innerText = product.desc || 'Deskripsi produk kualitas tinggi dengan garansi mutu resmi HOTEL OFFICIAL.';
    document.getElementById('pdp-qty-display').innerText = pdpQuantity;

    // Reset Size Buttons Active State
    selectSize('M');

    // Wishlist Button State
    const isFav = wishlist.has(product.id);
    const pdpWishlistBtn = document.getElementById('pdp-page-wishlist-btn');
    const pdpHeartIcon = document.getElementById('pdp-page-heart-icon');
    
    pdpWishlistBtn.onclick = (e) => {
        e.stopPropagation();
        toggleWishlist(product.id);
        const updatedFav = wishlist.has(product.id);
        pdpHeartIcon.className = `w-5 h-5 ${updatedFav ? 'fill-red-500 text-red-500' : 'text-white'}`;
    };
    pdpHeartIcon.className = `w-5 h-5 ${isFav ? 'fill-red-500 text-red-500' : 'text-white'}`;

    // Add to Bag Button Event
    const addCartBtn = document.getElementById('pdp-page-add-cart-btn');
    addCartBtn.onclick = () => {
        addToCartWithDetails(product.id, selectedSize, pdpQuantity);
    };

    lucide.createIcons();
}

function selectSize(size) {
    selectedSize = size;
    const buttons = document.querySelectorAll('#pdp-size-options .size-btn');
    buttons.forEach(btn => {
        if (btn.getAttribute('data-size') === size) {
            btn.className = 'size-btn px-4 py-2 border-2 border-amber-600 bg-amber-500/10 rounded-lg text-xs font-semibold text-amber-700 transition-all shadow-sm';
        } else {
            btn.className = 'size-btn px-4 py-2 border border-zinc-300 rounded-lg text-xs font-semibold text-zinc-800 hover:border-zinc-800 transition-all bg-white';
        }
    });
}

function adjustPdpQty(delta) {
    pdpQuantity = Math.max(1, pdpQuantity + delta);
    document.getElementById('pdp-qty-display').innerText = pdpQuantity;
}

function addToCartWithDetails(productId, size, qty) {
    const product = PRODUCTS.find(p => p.id === productId);
    if (!product) return;

    const existing = cart.find(item => item.id === productId && item.size === size);
    if (existing) {
        existing.qty += qty;
    } else {
        cart.push({ ...product, size: size, qty: qty });
    }

    updateCartUI();
    toggleCartDrawer();
    const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS['English'];
    showToast(`${dict.toast_added} ${product.title} (Size ${size})`);
}

