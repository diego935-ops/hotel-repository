function addToCart(productId) {
    const product = PRODUCTS.find(p => p.id === productId);
    if (!product) return;

    addToCartWithDetails(productId, 'M', 1);
}

function updateCartUI() {
    const countBadge = document.getElementById('cart-count');
    if (countBadge) {
        const totalCount = cart.reduce((acc, item) => acc + item.qty, 0);
        countBadge.innerText = totalCount;
    }

    const drawerContainer = document.getElementById('cart-drawer-items');
    if (!drawerContainer) return;
    drawerContainer.innerHTML = '';

    const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS['English'];
    let totalIDR = 0;

    if (cart.length === 0) {
        drawerContainer.innerHTML = `<p class="text-xs text-zinc-500 font-mono text-center py-8">${dict.cart_empty}</p>`;
    } else {
        cart.forEach((item, index) => {
            totalIDR += item.priceIDR * item.qty;
            const itemFormatted = formatPrice(item.priceIDR);
            const el = document.createElement('div');
            el.className = 'flex items-center gap-3 bg-zinc-900 p-2.5 border border-zinc-800 rounded';
            el.innerHTML = `
                <img src="${item.img}" class="w-12 h-14 object-cover rounded">
                <div class="flex-grow text-xs">
                    <h5 class="text-white font-medium uppercase text-[11px]">${item.title}</h5>
                    <p class="text-zinc-400 text-[10px] font-mono">Size: <span class="text-amber-400 font-bold">${item.size || 'M'}</span></p>
                    <p class="text-amber-400/90 font-mono text-[11px]">${itemFormatted} x ${item.qty}</p>
                </div>
                <button onclick="removeFromCart(${index})" class="text-zinc-500 hover:text-rose-400 p-1">
                    <i data-lucide="trash-2" class="w-4 h-4"></i>
                </button>
            `;
            drawerContainer.appendChild(el);
        });
    }

    const totalEl = document.getElementById('cart-total-price');
    if (totalEl) totalEl.innerText = formatPrice(totalIDR);
    lucide.createIcons();
}

function removeFromCart(index) {
    cart.splice(index, 1);
    updateCartUI();
}

function toggleCartDrawer() {
    const drawer = document.getElementById('cart-drawer');
    drawer.classList.toggle('translate-x-full');
}

function checkoutCart() {
    const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS['English'];
    if (cart.length === 0) {
        showToast(dict.toast_empty_cart, 'error');
        return;
    }
    cart = [];
    updateCartUI();
    toggleCartDrawer();
    showToast(dict.toast_checkout);
}

function toggleSearchModal() {
    const modal = document.getElementById('search-modal');
    modal.classList.toggle('hidden');
    if (!modal.classList.contains('hidden')) {
        document.getElementById('search-input').focus();
    }
}

function performSearch(query) {
    const res = document.getElementById('search-results');
    const q = query.trim().toLowerCase();
    const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS['English'];

    if (!q) {
        res.innerHTML = `<p class="text-xs text-zinc-500 font-mono text-center py-4">${dict.search_hint}</p>`;
        return;
    }

    const matches = PRODUCTS.filter(p => p.title.toLowerCase().includes(q) || p.category.toLowerCase().includes(q));
    res.innerHTML = '';

    if (matches.length === 0) {
        res.innerHTML = `<p class="text-xs text-zinc-500 font-mono text-center py-4">${dict.search_no_results}</p>`;
        return;
    }

    matches.forEach(p => {
        const row = document.createElement('div');
        row.className = 'flex items-center justify-between p-2 bg-zinc-800/60 hover:bg-zinc-800 rounded cursor-pointer';
        row.onclick = () => { showSection('pdp', p.id); toggleSearchModal(); };
        row.innerHTML = `
            <div class="flex items-center gap-3">
                <img src="${p.img}" class="w-10 h-10 object-cover rounded">
                <div>
                    <p class="text-xs text-white font-medium uppercase">${p.title}</p>
                    <p class="text-[10px] text-amber-400 font-mono">${formatPrice(p.priceIDR)}</p>
                </div>
            </div>
            <span class="text-[10px] bg-white text-black px-2 py-1 font-bold rounded uppercase">${dict.btn_buy}</span>
        `;
        res.appendChild(row);
    });
}

